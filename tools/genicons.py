#!/usr/bin/env python3
"""registry.json -> web/src/components/icons/index.tsx"""
import json, re, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'web', 'src', 'components', 'icons')
reg = json.load(open(os.path.join(root, 'registry.json')))
lines = ["// Generated by tools/genicons.py from the Laravel Blade inline SVGs. Do not edit.", "import type { SVGProps } from 'react';", "type P = SVGProps<SVGSVGElement>;", ""]
for h, svg in sorted(reg.items()):
    svg = re.sub(r'^<svg\b((?:[^>"\']|"[^"]*"|\'[^\']*\')*?)(/?)>', lambda m: '<svg' + m.group(1) + ' {...p}' + m.group(2) + '>', svg, count=1)
    svg = re.sub(r'(?<=[\s<])((?:stroke|fill|clip|stop|flood)-[a-z]+)=', lambda m: re.sub(r'-(\w)', lambda mm: mm.group(1).upper(), m.group(1)) + '=', svg)
    lines.append("export const I%s = (p: P) => (%s);" % (h, svg))
open(os.path.join(root, 'index.tsx'), 'w').write('\n'.join(lines) + '\n')
print(len(reg), 'icons')
